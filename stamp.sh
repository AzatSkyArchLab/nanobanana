#!/bin/sh
# Проставляет версию во входной модуль и в стили перед деплоем.
#
# GitHub Pages отдаёт файлы с max-age=600, поэтому без смены адреса браузер
# десять минут берёт старые JS и CSS из кеша и может склеить их со свежим HTML.
# Версия из адреса app.js протаскивается во все импорты (см. js/app.js).
# Библиотеки в js/vendor не версионируются: версия уже в имени их папки.
set -e
cd "$(dirname "$0")"
V=$(date -u +%Y%m%d%H%M)
perl -pi -e "s#((?:js/app\.js|styles\.css)\?v=)\d+#\${1}$V#g" index.html
printf '{"build": "%s"}\n' "$V" > version.json
echo "версия $V"
